function validatePatient(patient){

   const errors=[];

   if(!patient.fullName){

       errors.push("نام و نام خانوادگی الزامی است.");

   }

   if(!patient.gender){

       errors.push("جنسیت الزامی است.");

   }

   if(!patient.mobile){

       errors.push("شماره تماس الزامی است.");

   }

   return{

       valid:errors.length===0,

       errors

   };

}

