const SystemErrors=[];

/* ==========================================================
   REGISTER ERROR
========================================================== */

function addSystemError(error){

    SystemErrors.push({

        id:SystemErrors.length+1,

        date:getCurrentPersianDate(),

        time:getCurrentTime(),

        ...error

    });

}

/* ==========================================================
   GET ERRORS
========================================================== */

function getSystemErrors(){

    return SystemErrors;

}

