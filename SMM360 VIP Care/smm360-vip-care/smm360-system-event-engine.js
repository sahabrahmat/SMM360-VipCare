const SystemEvents=[];

/* ==========================================================
   REGISTER EVENT
========================================================== */

function addSystemEvent(event){

    SystemEvents.push({

        id:SystemEvents.length+1,

        date:getCurrentPersianDate(),

        time:getCurrentTime(),

        ...event

    });

}

/* ==========================================================
   GET EVENTS
========================================================== */

function getSystemEvents(){

    return SystemEvents;

}

