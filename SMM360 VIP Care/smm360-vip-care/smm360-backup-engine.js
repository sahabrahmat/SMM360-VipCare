const BackupHistory=[];

/* ==========================================================
   REGISTER BACKUP
========================================================== */

function registerBackup(info){

    BackupHistory.push({

        id:BackupHistory.length+1,

        date:getCurrentPersianDate(),

        time:getCurrentTime(),

        ...info

    });

}

/* ==========================================================
   GET BACKUPS
========================================================== */

function getBackupHistory(){

    return BackupHistory;

}

